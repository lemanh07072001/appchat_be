import { ConnectorCheckout } from './connector-checkout.service';
import { OrderStatusEnum } from '../enum/order.enum';

describe('Transactional Connector checkout', () => {
  const id = '507f1f77bcf86cd799439011';
  function fixture(enabled = 'true') {
    const query = { select: jest.fn().mockReturnThis(), lean: jest.fn().mockReturnThis(), exec: jest.fn().mockResolvedValue(null) };
    const events: string[] = [];
    const session = { withTransaction: jest.fn(async callback => callback()), endSession: jest.fn() };
    const orders = { findOne: jest.fn().mockReturnValue(query), create: jest.fn(async (_rows: any[], _options: any) => { events.push('order'); }),
      db: { startSession: jest.fn().mockResolvedValue(session) } };
    const users = { findOneAndUpdate: jest.fn((_filter: any, _update: any, _options: any) => ({ lean: jest.fn().mockReturnThis(), exec: jest.fn(async () => { events.push('debit'); return { money: 900 }; }) })) };
    const services = { updateOne: jest.fn(async () => { events.push('service'); return { modifiedCount: 1 }; }) };
    const wallet = { create: jest.fn(async (_rows: any[], _options: any) => { events.push('journal'); }) };
    const checkout = new ConnectorCheckout(orders as any, users as any, services as any, wallet as any, { get: () => enabled } as any);
    const binding = { accountId: id, connectorCode: 'example', connectorVersion: 1, packages: { '30': 'p1' } };
    const request = { userId: id, key: 'request-key', payload: { service_id: id, duration_days: 30 },
      service: { _id: id, name: 'Product', updatedAt: new Date(), connector_binding: binding } as any,
      order: { order_code: 'TEST-1', total_price: 100, price_per_unit: 100, quantity: 1, duration_days: 30,
        pricing_mode: 'duration', connector_purchase: { accountId: id, connectorCode: 'example', connectorVersion: 1, input: { packageId: 'p1' } } } };
    return { checkout, request, orders, query, users, services, wallet, session, events };
  }
  it('commits debit, order receipt and journal using the same transaction', async () => {
    const f = fixture(); const response = await f.checkout.commit(f.request);
    expect(f.events).toEqual(['service', 'debit', 'order', 'journal']);
    expect(response.data).toMatchObject({ balance_before: 1000, balance_after: 900, status: OrderStatusEnum.PENDING, start_date: null, end_date: null });
    expect(f.orders.create.mock.calls[0][1]).toEqual({ session: f.session });
    expect(f.wallet.create.mock.calls[0][1]).toEqual({ session: f.session });
    expect(f.users.findOneAndUpdate.mock.calls[0][2]).toEqual({ new: true, session: f.session });
    expect(f.session.endSession).toHaveBeenCalled();
  });
  it('keeps checkout disabled by default before any money or DB writes', async () => {
    const f = fixture('false');
    await expect(f.checkout.commit(f.request)).rejects.toThrow('chưa được kích hoạt');
    expect(f.users.findOneAndUpdate).not.toHaveBeenCalled();
    expect(f.orders.create).not.toHaveBeenCalled();
  });
  it('replays durable receipts even when deployment is disabled', async () => {
    const f = fixture('false');
    // Capture the real fingerprint generated by a successful transaction.
    const first = fixture(); await first.checkout.commit(first.request);
    const row = first.orders.create.mock.calls[0][0][0];
    f.query.exec.mockResolvedValue(row);
    expect(await f.checkout.commit(f.request)).toEqual(row.connector_checkout_response);
    expect(f.users.findOneAndUpdate).not.toHaveBeenCalled();
    await expect(f.checkout.replay(id, 'request-key', { duration_days: 7 })).rejects.toThrow('mismatch');
  });
  it('does not debit when admin changes the service snapshot', async () => {
    const f = fixture(); f.services.updateOne.mockResolvedValue({ modifiedCount: 0 });
    await expect(f.checkout.commit(f.request)).rejects.toThrow('Service changed');
    expect(f.users.findOneAndUpdate).not.toHaveBeenCalled();
  });
  it('fails within the transaction when the wallet journal cannot be saved', async () => {
    const f = fixture(); f.wallet.create.mockRejectedValue(new Error('journal unavailable'));
    await expect(f.checkout.commit(f.request)).rejects.toThrow('journal unavailable');
    expect(f.session.endSession).toHaveBeenCalled();
  });
});
